const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '../..');
const ts = require(path.join(root, 'node_modules/typescript'));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const repository = manifest.repository.url.replace(/^git\+/, '').replace(/\.git$/, '');
const sourceBase = `${repository}/blob/main/`;

// Every root export must have a canonical reference page. New exports fail
// generation until their documentation mapping is added here.
const references = {
  xxh32: ['value', './one-shot.md'],
  xxh64: ['value', './one-shot.md'],
  xxh3_64: ['value', './one-shot.md'],
  xxh3_128: ['value', './one-shot.md'],
  xxh32File: ['value', '../guides/files.md'],
  xxh64File: ['value', '../guides/files.md'],
  xxh3_64File: ['value', '../guides/files.md'],
  xxh3_128File: ['value', '../guides/files.md'],
  createHasher: ['value', './create-hasher.md'],
  hashStream: ['value', '../guides/streams.md'],
  HashInput: ['type', './types.md#hashinput'],
  HashAlgorithm: ['type', './types.md#hashalgorithm'],
  HashSeed: ['type', './types.md#hashseed'],
  HashStream: ['type', './types.md#hashstream'],
  HashOutput: ['type', './types.md#hashoutput'],
  HashResult: ['type', './types.md#hashresult'],
  HashOptions: ['type', './types.md#hashoptions'],
  FileHashOptions: ['type', './types.md#filehashoptions'],
  HashStreamOptions: ['type', './types.md#hashstreamoptions'],
  HashStreamSource: ['type', './types.md#hashstreamsource'],
};

function tableCell(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('|', '\\|')
    .replace(/\s+/g, ' ')
    .trim();
}

function sourceLink(declaration) {
  const source = declaration.getSourceFile();
  const relative = path.relative(root, source.fileName).split(path.sep).join('/');
  assert(
    !relative.startsWith('../') && !path.isAbsolute(relative),
    'Export source left the repository',
  );
  const line = source.getLineAndCharacterOfPosition(declaration.getStart(source)).line + 1;
  const encoded = relative.split('/').map(encodeURIComponent).join('/');
  return `[${relative}](${sourceBase}${encoded}#L${line})`;
}

function publicExports() {
  const configuration = ts.readConfigFile(path.join(root, 'tsconfig.json'), ts.sys.readFile);
  if (configuration.error)
    throw new Error(ts.flattenDiagnosticMessageText(configuration.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(configuration.config, ts.sys, root);
  if (parsed.errors.length)
    throw new Error(
      parsed.errors
        .map((error) => ts.flattenDiagnosticMessageText(error.messageText, '\n'))
        .join('\n'),
    );
  const entry = path.join(root, 'index.ts');
  const program = ts.createProgram([entry], { ...parsed.options, noEmit: true });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry);
  assert(source, 'Missing public entry source');
  const module = checker.getSymbolAtLocation(source);
  assert(module, 'The public entry is not a module');
  const exports = checker.getExportsOfModule(module);
  assert.deepEqual(
    exports.map((symbol) => symbol.getName()).sort(),
    Object.keys(references).sort(),
    'Public exports changed; add or remove their canonical documentation mappings',
  );
  return exports.map((exported) => {
    const name = exported.getName();
    const symbol =
      exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const [kind, reference] = references[name];
    const typeOnly = exported.getDeclarations()?.some(ts.isTypeOnlyExportDeclaration) ?? false;
    const actualKind = !typeOnly && symbol.flags & ts.SymbolFlags.Value ? 'value' : 'type';
    assert.equal(actualKind, kind, `The export kind changed for ${name}`);
    const declaration = symbol.getDeclarations()?.[0];
    assert(declaration, `Cannot resolve the source declaration for ${name}`);
    const description = ts.displayPartsToString(symbol.getDocumentationComment(checker));
    return {
      kind,
      row: `| [\`${name}\`](${reference}) | ${tableCell(description) || '—'} | ${sourceLink(declaration)} |`,
    };
  });
}

function catalogue() {
  const exports = publicExports();
  const sections = [
    ['value', 'Functions'],
    ['type', 'Types'],
  ];
  const content = [
    '---',
    'title: Public exports',
    'description: Public package exports, source comments and links to the full API reference.',
    'sidebar_position: 1',
    `custom_edit_url: ${repository}/edit/main/index.ts`,
    '---',
    '',
    '{/* Generated by website/scripts/generate-content.cjs from index.ts and source JSDoc. */}',
    '',
    'The package root exports the functions and types listed below. Follow a name for its complete API contract and examples.',
  ];
  for (const [kind, heading] of sections) {
    content.push(
      '',
      `## ${heading}`,
      '',
      '| Export | Source description | Source |',
      '| --- | --- | --- |',
    );
    content.push(...exports.filter((item) => item.kind === kind).map((item) => item.row));
  }
  return { content: content.join('\n') + '\n', exports };
}

function siteLink(destination) {
  if (/^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(destination)) return destination;
  const separator = destination.search(/[?#]/);
  const pathname = separator < 0 ? destination : destination.slice(0, separator);
  const suffix = separator < 0 ? '' : destination.slice(separator);
  const relative = path.posix.normalize(pathname);
  assert(!relative.startsWith('../'), `Contributor link leaves the repository: ${destination}`);
  if (relative.startsWith('docs/')) return `./${relative.slice(5)}${suffix}`;
  const encoded = relative.split('/').map(encodeURIComponent).join('/');
  return `${sourceBase}${encoded}${suffix}`;
}

function contributorPage() {
  const source = fs.readFileSync(path.join(root, 'CONTRIBUTING.md'), 'utf8');
  let fence;
  const body = source
    .split('\n')
    .map((line) => {
      const marker = line.match(/^\s*(`{3,}|~{3,})/);
      if (marker) {
        if (fence === undefined) fence = marker[1][0];
        else if (fence === marker[1][0]) fence = undefined;
        return line;
      }
      if (fence !== undefined) return line;
      return line.replace(
        /(\[[^\]]*\]\()([^\s)]+)(\))/g,
        (_, before, destination, after) => before + siteLink(destination) + after,
      );
    })
    .join('\n');
  return [
    '---',
    'title: Contributing',
    'description: Development setup, checks, native validation and publishing.',
    'sidebar_position: 100',
    `custom_edit_url: ${repository}/edit/main/CONTRIBUTING.md`,
    '---',
    '',
    '{/* Generated by website/scripts/generate-content.cjs from CONTRIBUTING.md. */}',
    '',
    body.trimEnd(),
    '',
  ].join('\n');
}

function main() {
  const { content, exports } = catalogue();
  const contributing = contributorPage();
  const api = path.join(root, 'docs/api');
  fs.mkdirSync(api, { recursive: true });
  fs.writeFileSync(path.join(api, 'exports.md'), content);
  fs.writeFileSync(path.join(root, 'docs/contributing.md'), contributing);
  console.log(
    `Generated public export catalogue (${exports.filter((item) => item.kind === 'value').length} functions, ` +
      `${exports.filter((item) => item.kind === 'type').length} types) and contributor page.`,
  );
}

main();
